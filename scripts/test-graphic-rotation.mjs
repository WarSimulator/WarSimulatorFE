import assert from 'node:assert/strict';
import { build } from 'esbuild';
const bundle = await build({ stdin: { contents: `export * from './src/features/simulation/lib/rotateGraphic'; export * from './src/features/simulation/lib/deploymentStorage'; export * from './src/features/simulation/lib/tacticalTasks'; export * from './src/features/simulation/lib/renderTacticalGraphic';`, resolveDir: process.cwd(), loader: 'ts' }, bundle: true, write: false, platform: 'node', format: 'esm', define: { 'import.meta.env': '{}' } });
const api = await import('data:text/javascript;base64,' + Buffer.from(bundle.outputFiles[0].text).toString('base64'));
const near = (a,b) => assert.ok(Math.abs(a-b)<1e-8, `${a} != ${b}`);
const line = {id:'rotation-line',type:'route',geometry:{type:'LineString',coordinates:[[127,37],[127.1,37]]}};
const center = api.rotationCenter(line);
const quarter = api.rotateGraphic(line,Math.PI/2,center);
near(quarter.geometry.coordinates[0][0],quarter.geometry.coordinates[1][0]);
const back = api.rotateGraphic(quarter,-Math.PI/2,center);
back.geometry.coordinates.forEach((p,i)=>p.forEach((v,j)=>near(v,line.geometry.coordinates[i][j])));
assert.deepEqual(line.geometry.coordinates,[[127,37],[127.1,37]]);
const polygon={id:'rotation-area',type:'area',geometry:{type:'Polygon',coordinates:[[[127,37],[127.1,37],[127.1,37.1],[127,37]],[[127.03,37.03],[127.04,37.03],[127.04,37.04],[127.03,37.03]]]}};
const rotated=api.rotateGraphic(polygon,0.7);
rotated.geometry.coordinates.forEach(ring=>assert.deepEqual(ring[0],ring.at(-1)));
const dateline={...line,geometry:{type:'LineString',coordinates:[[179.9,37],[-179.9,37]]}};
near(api.rotationCenter(dateline)[0],180);
assert.ok(api.graphicCoordinates(api.rotateGraphic(dateline,Math.PI/2)).every(p=>p.every(Number.isFinite)));
const task=api.tacticalTasks.find(t=>t.id==='2525E:340600');
const graphic=api.createTaskGraphic(task,'friendly',task.samplePoints);
const taskRotated=api.rotateGraphic(graphic,Math.PI/3);
assert.deepEqual(taskRotated.tacticalSymbol,graphic.tacticalSymbol);
assert.ok(api.renderTacticalGraphic(taskRotated,100000).length>0);
const saved=new Map();globalThis.window={localStorage:{getItem:k=>saved.get(k)??null,setItem:(k,v)=>saved.set(k,v)}};
const deployment=api.createEmptyDeployment('rotation-test','Rotation');deployment.tacticalGraphics=[quarter,rotated,taskRotated];
api.saveDeployment(deployment);
assert.deepEqual(api.getDeploymentById(deployment.id).tacticalGraphics,deployment.tacticalGraphics);
console.log('PASS: rotation direction, inverse, immutable geometry, polygon holes/closure, dateline, tactical task rendering and persistence.');
